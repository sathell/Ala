        ['kons-tel', 'contact-tel'].forEach(function (id) {
            var inp = document.getElementById(id);
            if (!inp) return;
            inp.addEventListener('input', function () { formatPhoneInput(this); });
            inp.addEventListener('keydown', function (e) {
                // Allow: backspace, delete, tab, arrows, home, end
                if ([8, 46, 9, 37, 38, 39, 40, 35, 36].indexOf(e.keyCode) !== -1) return;
                // Block non-digit keys (allow + only if field empty)
                if (e.key && !/^\d$/.test(e.key) && e.key !== '+') e.preventDefault();
            });
        });

        function formatPhoneInput(input) {
            var digits = input.value.replace(/\D/g, '').slice(0, 11);
            if (digits.length === 0) { input.value = ''; return; }
            var f = '+' + digits.slice(0, 2);
            if (digits.length > 2) f += ' ' + digits.slice(2, 5);
            if (digits.length > 5) f += ' ' + digits.slice(5, 8);
            if (digits.length > 8) f += ' ' + digits.slice(8, 11);
            input.value = f;

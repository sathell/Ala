        function fmt(n, dec) {
            if (dec === undefined) dec = 0;
            return n.toLocaleString('pl-PL', { minimumFractionDigits: dec, maximumFractionDigits: dec }) + ' zł';
        }

        function rataRowna(K, r, n) {
            if (r === 0) return K / n;
            return K * r * Math.pow(1 + r, n) / (Math.pow(1 + r, n) - 1);
        }

        function symulujOdsetki(kapital, stopa_m, rata, miesiace) {
            let K = kapital;
            let sum = 0;
            const lim = Math.min(miesiace, 600);
            for (let i = 0; i < lim; i++) {
                const ods = K * stopa_m;
                const kap = Math.min(rata - ods, K);
                if (kap <= 0) break;
                sum += ods;
                K -= kap;
            }
            return sum;
        }

        function oblicz() {
            const saldo = parseFloat(document.getElementById('k-saldo').value);
            const kOproc = parseFloat(document.getElementById('k-oprocent').value) / 100;
            const kOkresLat = parseInt(document.getElementById('k-okres').value);
            const kwota = parseFloat(document.getElementById('l-kwota').value);
            const lOproc = parseFloat(document.getElementById('l-oprocent').value) / 100;
            const lOkresMies = parseInt(document.getElementById('l-okres').value);
            const podatek = document.getElementById('l-podatek').checked;

            if (!saldo || !kOproc || !kOkresLat || !kwota || !lOproc || !lOkresMies) return;
            if (kwota >= saldo) { alert('Kwota nie może przekraczać salda kredytu.'); return; }

            // LOKATA
            const odsetkiBrutto = kwota * lOproc * (lOkresMies / 12);
            const belka = podatek ? odsetkiBrutto * 0.19 : 0;
            const odsetkiNetto = odsetkiBrutto - belka;
            const lEffNetto = (odsetkiNetto / kwota) / (lOkresMies / 12) * 100;

            // NADPŁATA
            const stopa_m = kOproc / 12;
            const kN = kOkresLat * 12;
            const rata = rataRowna(saldo, stopa_m, kN);

            const odsetkiBez = symulujOdsetki(saldo, stopa_m, rata, lOkresMies);
            const odsetkiPo = symulujOdsetki(saldo - kwota, stopa_m, rata, lOkresMies);
            const oszczednosc = odsetkiBez - odsetkiPo;
            const nEffNetto = (oszczednosc / kwota) / (lOkresMies / 12) * 100;

            // DOM
            document.getElementById('l-brutto').textContent = fmt(odsetkiBrutto, 2);
            document.getElementById('l-belka').textContent = podatek ? fmt(belka, 2) : '0,00 zł (pominięty)';
            document.getElementById('l-netto').textContent = fmt(odsetkiNetto, 2);
            document.getElementById('l-eff').textContent = lEffNetto.toFixed(2) + '%';
            document.getElementById('l-zysk').textContent = fmt(odsetkiNetto, 2);

            document.getElementById('n-przed').textContent = fmt(odsetkiBez, 2);
            document.getElementById('n-po').textContent = fmt(odsetkiPo, 2);
            document.getElementById('n-oszcz').textContent = fmt(oszczednosc, 2);
            document.getElementById('n-eff').textContent = nEffNetto.toFixed(2) + '%';
            document.getElementById('n-zysk').textContent = fmt(oszczednosc, 2);

            // Zwycięzca
            const cardL = document.getElementById('card-lokata');
            const cardN = document.getElementById('card-nadplata');
            cardL.classList.remove('winner');
            cardN.classList.remove('winner');
            document.querySelectorAll('.kalk-opt-winner-badge').forEach(e => e.remove());

            const winnerTitle = document.getElementById('winner-title');
            const winnerDesc = document.getElementById('winner-desc');
            const infoRow = document.getElementById('info-row');
            const roznica = Math.abs(oszczednosc - odsetkiNetto);
            const prog = kwota * 0.002;

            if (roznica < prog) {
                winnerTitle.textContent = 'Wynik praktycznie remisowy';
                winnerDesc.textContent = 'Różnica między zyskiem z lokaty (' + fmt(odsetkiNetto, 2) + ') a oszczędnością z nadpłaty (' + fmt(oszczednosc, 2) + ') jest minimalna. Rozważ inne czynniki: potrzeba płynności finansowej, zabezpieczenie poduszki oszczędnościowej, warunki umowy kredytowej.';
                infoRow.textContent = 'Oprocentowanie lokaty netto ≈ oprocentowanie kredytu. Żadna opcja nie jest wyraźnie lepsza.';
            } else if (odsetkiNetto > oszczednosc) {
                winnerTitle.textContent = 'Lokata jest korzystniejsza o ' + fmt(roznica, 2);
                winnerDesc.textContent = 'W ciągu ' + lOkresMies + ' miesięcy lokata przyniesie ' + fmt(odsetkiNetto, 2) + ' zysku netto, podczas gdy nadpłata zaoszczędziłaby ' + fmt(oszczednosc, 2) + ' na odsetkach. Pamiętaj — po zakończeniu lokaty sytuacja może się zmienić, szczególnie jeśli stopy procentowe wzrosną.';
                infoRow.textContent = 'Oprocentowanie lokaty netto (' + lEffNetto.toFixed(2) + '%) > oprocentowanie kredytu efektywne (' + nEffNetto.toFixed(2) + '%). Lokata się bardziej opłaca.';
                cardL.classList.add('winner');
                const b = document.createElement('div');
                b.className = 'kalk-opt-winner-badge';
                b.textContent = 'Korzystniejsze';
                cardL.appendChild(b);
            } else {
                winnerTitle.textContent = 'Nadpłata kredytu jest korzystniejsza o ' + fmt(roznica, 2);
                winnerDesc.textContent = 'W ciągu ' + lOkresMies + ' miesięcy nadpłata zaoszczędzi ' + fmt(oszczednosc, 2) + ' na odsetkach, podczas gdy lokata przyniosłaby ' + fmt(odsetkiNetto, 2) + ' netto. To typowa sytuacja przy obecnych poziomach stóp procentowych — oprocentowanie kredytów hipotecznych jest wyższe niż oferowane lokaty.';
                infoRow.textContent = 'Efektywne oprocentowanie nadpłaty (' + nEffNetto.toFixed(2) + '%) > oprocentowanie lokaty netto (' + lEffNetto.toFixed(2) + '%). Nadpłata się bardziej opłaca.';
                cardN.classList.add('winner');
                const b = document.createElement('div');
                b.className = 'kalk-opt-winner-badge';
                b.textContent = 'Korzystniejsze';
                cardN.appendChild(b);
            }

            const wyniki = document.getElementById('wyniki');
            wyniki.classList.add('visible');
            wyniki.scrollIntoView({ behavior: 'smooth', block: 'start' });
        }

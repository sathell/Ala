                    <h2>Jak działają obliczenia?</h2>
                    <p>Kalkulator porównuje dwa scenariusze w zadanym horyzoncie czasowym:</p>
                    <ul>
                        <li><strong>Lokata:</strong> pieniądze pracują na koncie oszczędnościowym. Odsetki są
                            opodatkowane podatkiem Belki (19%), chyba że wyłączysz tę opcję — wtedy wyniki pokazują zysk
                            brutto.</li>
                        <li><strong>Nadpłata:</strong> pieniądze idą na zmniejszenie kapitału kredytu. Efekt to
                            zaoszczędzone odsetki kredytowe za analizowany okres — bez podatku, bo to oszczędność, nie
                            dochód.</li>
                    </ul>

                    <h2>Kiedy lokata bije nadpłatę?</h2>
                    <p>Lokata jest korzystniejsza, gdy jej oprocentowanie netto (po podatku Belki) jest wyższe niż
                        oprocentowanie Twojego kredytu. Dziś — przy kredytach WIBOR+marża na poziomie 7–8% — trudno
                        znaleźć lokatę, która przebije efekt nadpłaty. Sytuacja może się zmienić, gdy stopy procentowe
                        zaczną spadać.</p>

                    <h2>Co jeszcze warto wziąć pod uwagę?</h2>
                    <ul>
                        <li><strong>Poduszka finansowa:</strong> zanim nadpłacisz kredyt, upewnij się, że masz
                            oszczędności na kilka miesięcy wydatków. Nadpłacone pieniądze trudno „wyjąć" z kredytu w
                            razie nagłej potrzeby.</li>
                        <li><strong>Zmienne oprocentowanie:</strong> jeśli masz kredyt ze zmienną stopą (WIBOR),
                            efektywność nadpłaty zmienia się razem z rynkiem.</li>
                        <li><strong>Prowizja za nadpłatę:</strong> w pierwszych 3 latach bank może pobierać prowizję.
                            Sprawdź umowę.</li>

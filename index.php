        function submitBooking() {
            var nameInp = document.getElementById('bk-name');
            var telInp = document.getElementById('bk-tel');
            var emailInp = document.getElementById('bk-email');
            var name = nameInp ? nameInp.value.trim() : '';
            var tel = telInp ? telInp.value.trim() : '';
            var email = emailInp ? emailInp.value.trim() : '';

            clearFieldErr('bk-name-err'); clearInvalid(nameInp);
            clearFieldErr('bk-tel-err'); clearInvalid(telInp);
            clearFieldErr('bk-email-err'); clearInvalid(emailInp);
            var genErr = document.getElementById('bk-err-general');
            if (genErr) genErr.classList.remove('show');

            var ok = true;
            if (!name) {
                showFieldErr('bk-name-err', 'Proszę podać imię i nazwisko.'); setInvalid(nameInp); ok = false;
            } else if (!validateName(name)) {
                showFieldErr('bk-name-err', 'Podaj imię i nazwisko — każde co najmniej 2 litery, oddzielone spacją.'); setInvalid(nameInp); ok = false;
            }
            if (!tel) {
                showFieldErr('bk-tel-err', 'Proszę podać numer telefonu.'); setInvalid(telInp); ok = false;
            } else if (!validatePhone(tel)) {
                showFieldErr('bk-tel-err', 'Podaj numer w formacie +XX XXX XXX XXX (znak "+" i dokładnie 11 cyfr).'); setInvalid(telInp); ok = false;
            }
            if (email && !validateEmail(email)) {
                showFieldErr('bk-email-err', 'Podaj poprawny adres e-mail (np. jan@example.com).'); setInvalid(emailInp); ok = false;
            }
            if (!ok) return;

            var submit = document.getElementById('bk-submit');
            var okDiv = document.getElementById('modal-ok');
            var detail = document.getElementById('modal-ok-detail');
            var opts = { weekday: 'long', day: 'numeric', month: 'long', year: 'numeric' };
            var dateStr = (pickedDate && pickedHour)
                ? pickedDate.toLocaleDateString('pl-PL', opts) + ' o ' + pickedHour
                : '';
            if (submit) submit.disabled = true;
            if (submit) submit.textContent = 'Wysyłanie…';

            var data = {
                name: name,
                tel: tel.replace(/\s/g, ''),
                email: email,
                topic: document.getElementById('bk-topic').value,
                message: document.getElementById('bk-note').value.trim(),
                date: pickedDate ? (
                    pickedDate.getFullYear() + '-' +
                    String(pickedDate.getMonth() + 1).padStart(2, '0') + '-' +
                    String(pickedDate.getDate()).padStart(2, '0')
                ) : '',
                hour: pickedHour || ''
            };
            fetch(CFG_ENDPOINT_BOOKING, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify(data)
            })
                .then(function (r) {
                    if (r.status === 409) {
                        // Termin właśnie zajęty przez kogoś innego
                        if (submit) { submit.disabled = false; submit.textContent = 'Potwierdź rezerwację'; }
                        if (genErr) {
                            genErr.textContent = 'Ten termin jest już zajęty. Wybierz inny termin.';
                            genErr.classList.add('show');
                        }
                        pickedDate = null; pickedHour = null;
                        fetchBookedSlots();
                        return;
                    }
                    if (r.status === 429) {
                        if (submit) { submit.disabled = false; submit.textContent = 'Potwierdź rezerwację'; }
                        if (genErr) {
                            genErr.textContent = 'Dzienny limit rezerwacji (2) został osiągnięty. Spróbuj ponownie jutro lub zadzwoń bezpośrednio.';
                            genErr.classList.add('show');
                        }
                        return;
                    }
                    if (!r.ok) throw new Error('HTTP ' + r.status);
                    if (submit) submit.style.display = 'none';
                    if (okDiv) okDiv.style.display = 'flex';
                    if (detail) detail.textContent = dateStr;
                    fetchBookedSlots();
                    setTimeout(function () { closeBookingModal(); }, 3500);
                })
                .catch(function () {
                    if (submit) { submit.disabled = false; submit.textContent = 'Potwierdź rezerwację'; }
                    if (genErr) {
                        genErr.textContent = 'Wystąpił błąd serwera. Spróbuj ponownie lub zadzwoń bezpośrednio.';
                        genErr.classList.add('show');
                    }
                });
        }</script>

